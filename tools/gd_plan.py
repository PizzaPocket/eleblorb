"""Write a settlement's plan as a generated GDScript class of constants, the one plan its game builder and
validator read (the pattern of scripts/city_plan.gd and scripts/kai_malie_plan.gd).

    from gd_plan import write_plan
    write_plan('PlantVillagePlan', 'plant_village_plan.gd', header_lines, dict(NAME=value, ...), source='tools/x.py')

Values are converted to GDScript literals: dicts to dictionaries, lists and tuples to arrays, numbers rounded to
centimetres (3 places), None to null. Keys become strings. Points stay plain arrays ([x, z] or [x, y, z]); the
header of each plan says which frame they are in, and the builder converts them.
"""
import math, os

def lit(v, depth=0):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    if isinstance(v, float):
        if math.isnan(v) or math.isinf(v): raise ValueError('a plan value is not finite')
        r = round(v, 3)
        return repr(int(r)) + '.0' if r == int(r) else repr(r)
    if isinstance(v, str): return '"' + v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
    if isinstance(v, dict):
        return '{' + ', '.join('%s: %s' % (lit(str(k)), lit(x, depth + 1)) for k, x in v.items()) + '}'
    if isinstance(v, (list, tuple)):
        return '[' + ', '.join(lit(x, depth + 1) for x in v) + ']'
    raise TypeError('cannot write %r to a plan' % type(v))

def write_plan(class_name, filename, header, consts, source):
    out = ['class_name %s' % class_name, 'extends RefCounted', '']
    out += ['## ' + h if h else '##' for h in header]
    out += ['##', '## GENERATED by %s: edit there and rerun it, never here.' % source, '']
    for k, v in consts.items():
        if isinstance(v, tuple) and len(v) == 2 and isinstance(v[0], str) and v[0].startswith('#'):
            out.append('## ' + v[0][1:].strip()); v = v[1]
        out.append('const %s := %s' % (k, lit(v)))
        out.append('')
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    path = os.path.join(root, 'scripts', filename)
    open(path, 'w').write('\n'.join(out).rstrip() + '\n')
    return path
